create or replace function public.normalize_player_username(p_username text)
returns text
language sql
immutable
as $$
  select lower(regexp_replace(trim(coalesce(p_username, '')), '[^a-z0-9_-]', '', 'g'));
$$;

create or replace function public.player_id_from_token(p_token text)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_player_id uuid;
begin
  select player_id into v_player_id
  from public.player_sessions
  where token = p_token and expires_at > now();

  if v_player_id is null then
    raise exception 'Invalid or expired session';
  end if;

  return v_player_id;
end;
$$;

create or replace function public.register_player(p_username text, p_password text)
returns table(session_token text, player_id uuid, username text)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_username text := public.normalize_player_username(p_username);
  v_player_id uuid;
  v_token text;
begin
  if length(v_username) < 3 then
    raise exception 'Username must be at least 3 letters or numbers';
  end if;

  if length(coalesce(p_password, '')) < 6 then
    raise exception 'Password must be at least 6 characters';
  end if;

  insert into public.players(username, password_hash)
  values (v_username, extensions.crypt(p_password, extensions.gen_salt('bf')))
  returning id into v_player_id;

  v_token := encode(extensions.gen_random_bytes(32), 'hex');
  insert into public.player_sessions(token, player_id) values (v_token, v_player_id);

  return query select v_token, v_player_id, v_username;
exception
  when unique_violation then
    raise exception 'That username already exists';
end;
$$;

create or replace function public.login_player(p_username text, p_password text)
returns table(session_token text, player_id uuid, username text)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_username text := public.normalize_player_username(p_username);
  v_player record;
  v_token text;
begin
  select p.id, p.username, p.password_hash, p.banned_at, p.ban_reason into v_player
  from public.players p
  where p.username = v_username;

  if v_player.id is null or v_player.password_hash <> extensions.crypt(p_password, v_player.password_hash) then
    raise exception 'Wrong username or password';
  end if;

  if v_player.banned_at is not null then
    raise exception 'This account is banned: %', coalesce(v_player.ban_reason, 'No reason provided');
  end if;

  v_token := encode(extensions.gen_random_bytes(32), 'hex');
  insert into public.player_sessions(token, player_id) values (v_token, v_player.id);

  return query select v_token, v_player.id, v_player.username;
end;
$$;

create or replace function public.get_clicker_save(p_token text)
returns table(username text, save jsonb, max_points numeric, updated_at timestamptz)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_player_id uuid := public.player_id_from_token(p_token);
begin
  return query
  select p.username, s.save, coalesce(s.max_points, 0), s.updated_at
  from public.players p
  left join public.clicker_saves s on s.player_id = p.id
  where p.id = v_player_id;
end;
$$;

create or replace function public.save_clicker(p_token text, p_save jsonb, p_max_points numeric)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_player_id uuid := public.player_id_from_token(p_token);
begin
  insert into public.clicker_saves(player_id, save, max_points, updated_at)
  values (v_player_id, coalesce(p_save, '{}'::jsonb), greatest(coalesce(p_max_points, 0), 0), now())
  on conflict (player_id) do update set
    save = excluded.save,
    max_points = greatest(public.clicker_saves.max_points, excluded.max_points),
    updated_at = now();
end;
$$;

create or replace function public.delete_clicker_save(p_token text)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_player_id uuid := public.player_id_from_token(p_token);
begin
  delete from public.clicker_saves where player_id = v_player_id;
end;
$$;

create or replace function public.require_alex_admin(p_token text)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_player_id uuid := public.player_id_from_token(p_token);
  v_username text;
begin
  select username into v_username from public.players where id = v_player_id;
  if v_username <> 'alex' then
    raise exception 'Admin access denied';
  end if;
  return v_player_id;
end;
$$;

create or replace function public.list_public_players(p_token text default '')
returns table(username text, created_at timestamptz)
language sql
security definer
set search_path = public
as $$
  select p.username, p.created_at
  from public.players p
  where p.banned_at is null
  order by p.username
  limit 250;
$$;

create or replace function public.admin_ban_player(p_token text, p_target_username text, p_reason text)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_admin_id uuid := public.require_alex_admin(p_token);
  v_target_username text := public.normalize_player_username(p_target_username);
  v_target_id uuid;
begin
  if length(trim(coalesce(p_reason, ''))) < 3 then
    raise exception 'A ban reason is required';
  end if;

  select id into v_target_id from public.players where username = v_target_username;
  if v_target_id is null then
    raise exception 'Target user not found';
  end if;

  update public.players
  set banned_at = now(), ban_reason = trim(p_reason), updated_at = now()
  where id = v_target_id;

  delete from public.player_sessions where player_id = v_target_id;

  insert into public.admin_actions(admin_player_id, target_player_id, target_username, action, reason)
  values (v_admin_id, v_target_id, v_target_username, 'ban', trim(p_reason));
end;
$$;


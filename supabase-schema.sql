-- Run this once in Supabase Dashboard -> SQL Editor for the alex.fun project.
-- This version uses game-only usernames/passwords. No email addresses are used.
-- It stores password hashes with pgcrypto and gives the browser a random session token.

create schema if not exists extensions;
create extension if not exists pgcrypto with schema extensions;


-- If you previously ran the email/Auth version of this setup, those old tables have
-- different columns. This resets only the alex.fun game tables so the no-email
-- username/password version can be installed cleanly.
do $$
begin
  if exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'clicker_saves' and column_name = 'user_id'
  ) then
    drop table if exists public.clicker_saves cascade;
  end if;

  if exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'suggestions' and column_name = 'user_id'
  ) then
    drop table if exists public.suggestions cascade;
  end if;
end $$;

create table if not exists public.players (
  id uuid primary key default extensions.gen_random_uuid(),
  username text not null unique,
  password_hash text not null,
  banned_at timestamptz,
  ban_reason text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.players add column if not exists banned_at timestamptz;
alter table public.players add column if not exists ban_reason text;

create table if not exists public.player_sessions (
  token text primary key,
  player_id uuid not null references public.players(id) on delete cascade,
  created_at timestamptz not null default now(),
  expires_at timestamptz not null default now() + interval '180 days'
);

create table if not exists public.clicker_saves (
  player_id uuid primary key references public.players(id) on delete cascade,
  save jsonb not null default '{}'::jsonb,
  max_points numeric not null default 0,
  updated_at timestamptz not null default now()
);

create table if not exists public.infinite_craft_saves (
  player_id uuid primary key references public.players(id) on delete cascade,
  discoveries jsonb not null default '[]'::jsonb,
  updated_at timestamptz not null default now()
);

create table if not exists public.suggestions (
  id bigint generated by default as identity primary key,
  player_id uuid references public.players(id) on delete set null,
  username text,
  idea text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.recipe_cache (
  recipe_key text primary key,
  input_a text not null,
  input_b text not null,
  result_emoji text,
  result_name text,
  missing boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.admin_actions (
  id bigint generated by default as identity primary key,
  admin_player_id uuid references public.players(id) on delete set null,
  target_player_id uuid references public.players(id) on delete set null,
  target_username text not null,
  action text not null,
  reason text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.game_updates (
  id text primary key,

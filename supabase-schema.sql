create or replace function public.list_social_state(p_token text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_player_id uuid := public.player_id_from_token(p_token);
  v_state jsonb;
begin
  select jsonb_build_object(
    'users', (
      select coalesce(jsonb_agg(username order by username), '[]'::jsonb)
      from public.players
      where banned_at is null
    ),
    'friends', (
      select coalesce(jsonb_agg(friend_username order by friend_username), '[]'::jsonb)
      from (
        select case when f.player_a = v_player_id then pb.username else pa.username end friend_username
        from public.friendships f
        join public.players pa on pa.id = f.player_a
        join public.players pb on pb.id = f.player_b
        where f.player_a = v_player_id or f.player_b = v_player_id
      ) friend_rows
    ),
    'incomingRequests', (
      select coalesce(jsonb_agg(jsonb_build_object('id', fr.id, 'username', p.username, 'created_at', fr.created_at) order by fr.created_at desc), '[]'::jsonb)
      from public.friend_requests fr
      join public.players p on p.id = fr.requester_id
      where fr.recipient_id = v_player_id and fr.status = 'pending'
    ),
    'outgoingRequests', (
      select coalesce(jsonb_agg(p.username order by p.username), '[]'::jsonb)
      from public.friend_requests fr
      join public.players p on p.id = fr.recipient_id
      where fr.requester_id = v_player_id and fr.status = 'pending'
    ),
    'messages', (
      select coalesce(jsonb_agg(jsonb_build_object(
        'id', m.id,
        'from', sp.username,
        'to', rp.username,
        'body', m.body,
        'created_at', m.created_at,
        'mine', m.sender_id = v_player_id,
        'read_at', m.read_at
      ) order by m.created_at), '[]'::jsonb)
      from public.direct_messages m
      join public.players sp on sp.id = m.sender_id
      join public.players rp on rp.id = m.recipient_id
      where m.sender_id = v_player_id or m.recipient_id = v_player_id
    ),
    'notifications', (
      select coalesce(jsonb_agg(jsonb_build_object(
        'id', n.id,
        'kind', n.kind,
        'from', n.actor_username,
        'body', n.body,
        'created_at', n.created_at,
        'read_at', n.read_at
      ) order by n.created_at desc), '[]'::jsonb)
      from (
        select * from public.notifications
        where player_id = v_player_id
        order by created_at desc
        limit 30
      ) n
    )
  ) into v_state;
  return v_state;
end;
$$;

create or replace function public.get_infinite_craft_save(p_token text)
returns table(username text, discoveries jsonb, updated_at timestamptz)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_player_id uuid := public.player_id_from_token(p_token);
begin
  return query
  select p.username, coalesce(s.discoveries, '[]'::jsonb), s.updated_at
  from public.players p
  left join public.infinite_craft_saves s on s.player_id = p.id
  where p.id = v_player_id;
end;
$$;

create or replace function public.save_infinite_craft(p_token text, p_discoveries jsonb)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_player_id uuid := public.player_id_from_token(p_token);
  v_discoveries jsonb := coalesce(p_discoveries, '[]'::jsonb);
begin
  if jsonb_typeof(v_discoveries) <> 'array' then
    raise exception 'Discoveries must be a JSON array';
  end if;

  insert into public.infinite_craft_saves(player_id, discoveries, updated_at)
  values (v_player_id, v_discoveries, now())
  on conflict (player_id) do update set
    discoveries = excluded.discoveries,
    updated_at = now();
end;
$$;

create or replace function public.delete_infinite_craft_save(p_token text)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_player_id uuid := public.player_id_from_token(p_token);
begin
  delete from public.infinite_craft_saves where player_id = v_player_id;
end;
$$;

create or replace function public.get_clicker_leaderboard()
returns table(username text, max_points numeric, updated_at timestamptz)
language sql
security definer
set search_path = public
as $$
  select p.username, s.max_points, s.updated_at
  from public.clicker_saves s
  join public.players p on p.id = s.player_id
  order by s.max_points desc
  limit 10;
$$;

create or replace function public.submit_suggestion(p_token text, p_idea text)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_player_id uuid;
  v_username text;
begin
  if length(trim(coalesce(p_idea, ''))) < 2 then
    return;
  end if;

  if p_token is not null and p_token <> '' then
    v_player_id := public.player_id_from_token(p_token);
    select username into v_username from public.players where id = v_player_id;
  end if;

  insert into public.suggestions(player_id, username, idea)
  values (v_player_id, v_username, trim(p_idea));
end;
$$;


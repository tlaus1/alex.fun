create or replace function public.normalize_player_username(p_username text)
returns text
language sql
immutable
as $$
  select lower(regexp_replace(trim(coalesce(p_username, '')), '[^a-z0-9_-]', '', 'g'));
$$;

create or replace function public.player_id_from_token(p_token text)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_player_id uuid;
  v_player record;
begin
  select player_id into v_player_id
  from public.player_sessions
  where token = p_token and expires_at > now();

  if v_player_id is null then
    raise exception 'Invalid or expired session';
  end if;

  select id, banned_at, ban_expires_at, ban_reason into v_player
  from public.players
  where id = v_player_id;

  if v_player.banned_at is not null and (v_player.ban_expires_at is null or v_player.ban_expires_at > now()) then
    delete from public.player_sessions where player_id = v_player_id;
    raise exception 'This account is banned: %', coalesce(v_player.ban_reason, 'No reason provided');
  elsif v_player.banned_at is not null and v_player.ban_expires_at <= now() then
    update public.players
    set banned_at = null, ban_reason = null, ban_expires_at = null, updated_at = now()
    where id = v_player_id;
  end if;

  return v_player_id;
end;
$$;

create or replace function public.register_player(p_username text, p_password text)
returns table(session_token text, player_id uuid, username text)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_username text := public.normalize_player_username(p_username);
  v_player_id uuid;
  v_token text;
begin
  if length(v_username) < 3 then
    raise exception 'Username must be at least 3 letters or numbers';
  end if;

  if length(coalesce(p_password, '')) < 6 then
    raise exception 'Password must be at least 6 characters';
  end if;

  insert into public.players(username, password_hash)
  values (v_username, extensions.crypt(p_password, extensions.gen_salt('bf')))
  returning id into v_player_id;

  v_token := encode(extensions.gen_random_bytes(32), 'hex');
  insert into public.player_sessions(token, player_id) values (v_token, v_player_id);

  return query select v_token, v_player_id, v_username;
exception
  when unique_violation then
    raise exception 'That username already exists';
end;
$$;

create or replace function public.login_player(p_username text, p_password text)
returns table(session_token text, player_id uuid, username text)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_username text := public.normalize_player_username(p_username);
  v_player record;
  v_token text;
begin
  select p.id, p.username, p.password_hash, p.banned_at, p.ban_reason, p.ban_expires_at into v_player
  from public.players p
  where p.username = v_username;

  if v_player.id is null or v_player.password_hash <> extensions.crypt(p_password, v_player.password_hash) then
    raise exception 'Wrong username or password';
  end if;

  if v_player.banned_at is not null and (v_player.ban_expires_at is null or v_player.ban_expires_at > now()) then
    raise exception 'This account is banned: %', coalesce(v_player.ban_reason, 'No reason provided');
  elsif v_player.banned_at is not null and v_player.ban_expires_at <= now() then
    update public.players
    set banned_at = null, ban_reason = null, ban_expires_at = null, updated_at = now()
    where id = v_player.id;
  end if;

  v_token := encode(extensions.gen_random_bytes(32), 'hex');
  insert into public.player_sessions(token, player_id) values (v_token, v_player.id);

  return query select v_token, v_player.id, v_player.username;
end;
$$;

create or replace function public.get_ban_status(p_username text)
returns table(username text, banned boolean, reason text, banned_at timestamptz, ban_expires_at timestamptz, remaining_seconds bigint)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_username text := public.normalize_player_username(p_username);
  v_player record;
begin
  select p.username, p.banned_at, p.ban_reason, p.ban_expires_at into v_player
  from public.players p
  where p.username = v_username;

  if v_player.username is null then
    return query select v_username, false, null::text, null::timestamptz, null::timestamptz, null::bigint;
    return;
  end if;

  if v_player.banned_at is not null and v_player.ban_expires_at is not null and v_player.ban_expires_at <= now() then
    update public.players
    set banned_at = null, ban_reason = null, ban_expires_at = null, updated_at = now()
    where public.players.username = v_username;
    return query select v_username, false, null::text, null::timestamptz, null::timestamptz, null::bigint;
    return;
  end if;

  return query select
    v_player.username,
    v_player.banned_at is not null,
    v_player.ban_reason,
    v_player.banned_at,
    v_player.ban_expires_at,
    case
      when v_player.banned_at is null then null::bigint
      when v_player.ban_expires_at is null then null::bigint
      else greatest(0, floor(extract(epoch from (v_player.ban_expires_at - now())))::bigint)
    end;
end;
$$;

create or replace function public.get_clicker_save(p_token text)
returns table(username text, save jsonb, max_points numeric, updated_at timestamptz)

create or replace function public.send_friend_request(p_token text, p_target_username text)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_player_id uuid := public.player_id_from_token(p_token);
  v_actor_username text;
  v_target_username text := public.normalize_player_username(p_target_username);
  v_target_id uuid;
begin
  select username into v_actor_username from public.players where id = v_player_id;
  select id into v_target_id from public.players where username = v_target_username and banned_at is null;
  if v_target_id is null then raise exception 'User not found'; end if;
  if v_target_id = v_player_id then raise exception 'You cannot friend yourself'; end if;

  insert into public.friend_requests(requester_id, recipient_id, status, updated_at)
  values (v_player_id, v_target_id, 'pending', now())
  on conflict (requester_id, recipient_id) do update set status = 'pending', updated_at = now();

  insert into public.notifications(player_id, actor_id, actor_username, kind, body)
  values (v_target_id, v_player_id, v_actor_username, 'friend_request', v_actor_username || ' sent you a friend request');
end;
$$;

create or replace function public.respond_friend_request(p_token text, p_request_id bigint, p_accept boolean)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_player_id uuid := public.player_id_from_token(p_token);
  v_request record;
  v_actor_username text;
  v_low uuid;
  v_high uuid;
begin
  select fr.*, p.username requester_username into v_request
  from public.friend_requests fr
  join public.players p on p.id = fr.requester_id
  where fr.id = p_request_id and fr.recipient_id = v_player_id and fr.status = 'pending';
  if v_request.id is null then raise exception 'Friend request not found'; end if;
  select username into v_actor_username from public.players where id = v_player_id;

  update public.friend_requests
  set status = case when p_accept then 'accepted' else 'declined' end, updated_at = now()
  where id = p_request_id;

  if p_accept then
    v_low := least(v_player_id, v_request.requester_id);
    v_high := greatest(v_player_id, v_request.requester_id);
    insert into public.friendships(player_a, player_b)
    values (v_low, v_high)
    on conflict do nothing;
    insert into public.notifications(player_id, actor_id, actor_username, kind, body)
    values (v_request.requester_id, v_player_id, v_actor_username, 'friend_accept', v_actor_username || ' accepted your friend request');
  end if;
end;
$$;

create or replace function public.send_direct_message(p_token text, p_recipient_username text, p_body text)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_player_id uuid := public.player_id_from_token(p_token);
  v_actor_username text;
  v_recipient_username text := public.normalize_player_username(p_recipient_username);
  v_recipient_id uuid;
  v_body text := trim(coalesce(p_body, ''));
begin
  if length(v_body) < 1 then return; end if;
  if length(v_body) > 1000 then raise exception 'Message is too long'; end if;
  select username into v_actor_username from public.players where id = v_player_id;
  select id into v_recipient_id from public.players where username = v_recipient_username and banned_at is null;
  if v_recipient_id is null then raise exception 'Recipient not found'; end if;
  if v_recipient_id = v_player_id then raise exception 'You cannot message yourself'; end if;

  insert into public.direct_messages(sender_id, recipient_id, body)
  values (v_player_id, v_recipient_id, v_body);
  insert into public.notifications(player_id, actor_id, actor_username, kind, body)
  values (v_recipient_id, v_player_id, v_actor_username, 'message', 'New message from ' || v_actor_username);
end;
$$;


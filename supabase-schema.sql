create or replace function public.get_clicker_leaderboard()
returns table(username text, max_points numeric, updated_at timestamptz)
language sql
security definer
set search_path = public
as $$
  select p.username, s.max_points, s.updated_at
  from public.clicker_saves s
  join public.players p on p.id = s.player_id
  order by s.max_points desc
  limit 10;
$$;

create or replace function public.submit_suggestion(p_token text, p_idea text)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_player_id uuid;
  v_username text;
begin
  if length(trim(coalesce(p_idea, ''))) < 2 then
    return;
  end if;

  if p_token is not null and p_token <> '' then
    v_player_id := public.player_id_from_token(p_token);
    select username into v_username from public.players where id = v_player_id;
  end if;

  insert into public.suggestions(player_id, username, idea)
  values (v_player_id, v_username, trim(p_idea));
end;
$$;


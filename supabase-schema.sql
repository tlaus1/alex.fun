create or replace function public.admin_ban_player(p_token text, p_target_username text, p_reason text, p_duration_minutes integer default null)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_admin_id uuid := public.require_alex_admin(p_token);
  v_target_username text := public.normalize_player_username(p_target_username);
  v_target_id uuid;
  v_expires_at timestamptz;
begin
  if length(trim(coalesce(p_reason, ''))) < 3 then
    raise exception 'A ban reason is required';
  end if;

  if p_duration_minutes is not null and p_duration_minutes > 0 then
    v_expires_at := now() + make_interval(mins => p_duration_minutes);
  end if;

  select id into v_target_id from public.players where username = v_target_username;
  if v_target_id is null then
    raise exception 'Target user not found';
  end if;

  update public.players
  set banned_at = now(), ban_reason = trim(p_reason), ban_expires_at = v_expires_at, updated_at = now()
  where id = v_target_id;

  delete from public.player_sessions where player_id = v_target_id;

  insert into public.admin_actions(admin_player_id, target_player_id, target_username, action, reason)
  values (v_admin_id, v_target_id, v_target_username, 'ban', trim(p_reason) || coalesce(' (' || p_duration_minutes || ' minutes)', ' (permanent)'));
end;
$$;

